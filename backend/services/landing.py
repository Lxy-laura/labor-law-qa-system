    def _build_service(self, q_type: str) -> Dict[str, Any]:
        """
        为指定问题类型构建落地服务

        参数:
            q_type: 问题类型

        返回:
            落地服务字典
        """
        # 确定推荐的热线
        if q_type in ["工资拖欠", "社保", "加班", "工伤", "年休假", "试用期"]:
            hotlines = ["12333", "12348"]
        elif q_type in ["违法解除", "经济补偿", "未签合同", "调岗降薪"]:
            hotlines = ["12348", "12333", "12351"]
        else:
            hotlines = ["12345", "12348"]

        hotline_str = "；".join([
            f"{num}（{self.HOTLINES[num]}）" for num in hotlines
        ])

        # 选择推荐机构
        institutions = self.INSTITUTIONS[:2]
        institution_str = "；".join([
            f"{inst['name']}（{inst['service']}）" for inst in institutions
        ])
        address_str = "；".join([
            inst["address"] for inst in institutions
        ])

        # 获取行动指引
        action_guide = self.ACTION_GUIDES.get(q_type, [
            "1. 收集并保存相关证据",
            "2. 与用人单位协商解决",
            "3. 拨打 12333 或 12348 咨询维权",
            "4. 协商不成可申请劳动仲裁"
        ])

        return {
            "service_type": q_type,
            "hotline": hotline_str,
            "institution": institution_str,
            "address": address_str,
            "action_guide": action_guide
        }
